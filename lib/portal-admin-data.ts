export function getStoredAdminProjects(): AdminProjectItem[] {
  if (typeof window === 'undefined') return INITIAL_ADMIN_PROJECTS;
  try {
    const raw = window.localStorage.getItem(STORAGE_KEYS.projects);
    if (!raw) {
      window.localStorage.setItem(STORAGE_KEYS.projects, JSON.stringify(INITIAL_ADMIN_PROJECTS));
      return INITIAL_ADMIN_PROJECTS;
    }
    return JSON.parse(raw);
  } catch {
    return INITIAL_ADMIN_PROJECTS;
  }
}

