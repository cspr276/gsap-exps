// Admin Data Store & Services for the Evalixa Admin Portal
// Synchronizes with localStorage and provides operational methods for
// projects, applications review, user management, and request workflows.

export interface AdminOverviewStats {
  totalUsers: number;
  ecsCount: number;
  employersCount: number;
  totalProjects: number;
  openProjectsCount: number;
  totalApplications: number;
  pendingReviewsCount: number;
  activeAssignmentsCount: number;
  completedDeliverablesCount: number;
  urgentRequestsCount: number;
}

export interface AdminProjectItem {
  id: string;
  title: string;
  summary: string;
  description: string;
  employerName: string;
  projectType: string;
  projectTypeLabel: string;
  difficulty: 'Beginner' | 'Intermediate' | 'Advanced' | 'Expert';
  modality: 'Code' | 'Text' | 'Multimodal' | 'Reasoning';
  compensation: string;
  hourlyRate: number;
  status: 'open' | 'in_progress' | 'completed' | 'closed';
  openings: number;
  applicantsCount: number;
  requiredSkills: string[];
  domains: string[];
  timeCommitment: string;
  createdAt: string;
}

export interface AdminApplicationItem {
  id: string;
  projectId: string;
  projectTitle: string;
  ecId: string;
  ecName: string;
  ecEmail: string;
  matchScore: number;
  status: 'submitted' | 'in_review' | 'shortlisted' | 'selected' | 'approved' | 'rejected';
  submittedAt: string;
  notes: string;
  skills: string[];
}

export interface AdminUserItem {
  id: string;
  name: string;
  email: string;
  role: 'admin' | 'ec' | 'employer';
  status: 'active' | 'suspended';
  verificationStatus: 'verified' | 'pending' | 'unverified';
  createdAt: string;
  lastLoginAt: string;
  headline?: string;
  skills?: string[];
  earnings?: number;
  companyName?: string;
}

export interface AdminPortalRequestItem {
  id: string;
  requestType: 'internship_certificate' | 'quit_job' | 'support_inquiry';
  requestTypeLabel: string;
  requesterId: string;
  requesterName: string;
  requesterEmail: string;
  status: 'submitted' | 'in_review' | 'approved' | 'rejected' | 'resolved';
  details: string;
  certificateId?: string;
  createdAt: string;
}

export interface AdminAuditLogItem {
  id: string;
  action: string;
  target: string;
  actor: string;
  at: string;
}

