export function appendAuditLog(action: string, target: string, actor = 'web-admin@evalixa.com') {
  const logs = getStoredAuditLogs();
  const entry: AdminAuditLogItem = {
    id: `log_${Date.now().toString(36)}`,
    action,
    target,
    actor,
    at: 'Just now',
  };
  const updated = [entry, ...logs.slice(0, 99)];
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEYS.logs, JSON.stringify(updated));
  }
  return entry;
}

export function getAdminOverviewMetrics(): AdminOverviewStats {
  const users = getStoredAdminUsers();
  const projects = getStoredAdminProjects();
  const apps = getStoredAdminApplications();
  const reqs = getStoredAdminRequests();

  const ecs = users.filter((u) => u.role === 'ec');
  const employers = users.filter((u) => u.role === 'employer');
  const openProjects = projects.filter((p) => p.status === 'open');
  const pendingReviews = apps.filter((a) => a.status === 'submitted' || a.status === 'in_review');
  const activeAssignments = apps.filter((a) => a.status === 'approved' || a.status === 'selected');
  const urgentReqs = reqs.filter((r) => r.status === 'submitted' || r.status === 'in_review');

  return {
    totalUsers: users.length,
    ecsCount: ecs.length,
    employersCount: employers.length,
    totalProjects: projects.length,
    openProjectsCount: openProjects.length,
    totalApplications: apps.length,
    pendingReviewsCount: pendingReviews.length,
    activeAssignmentsCount: activeAssignments.length,
    completedDeliverablesCount: 42,
    urgentRequestsCount: urgentReqs.length,
  };
}

export function createAdminProject(input: {
  title: string;
  summary: string;
  description: string;
  employerName?: string;
  projectType: string;
  difficulty: 'Beginner' | 'Intermediate' | 'Advanced' | 'Expert';
  modality: 'Code' | 'Text' | 'Multimodal' | 'Reasoning';
  compensation: string;
  hourlyRate: number;
  openings: number;
  requiredSkills: string[];
  domains: string[];
  timeCommitment: string;
}): AdminProjectItem {
  const projects = getStoredAdminProjects();
  const newProj: AdminProjectItem = {
    id: `proj_${Date.now().toString(36)}`,
    title: input.title.trim(),
    summary: input.summary.trim(),
    description: input.description.trim(),
    employerName: input.employerName?.trim() || 'Evalixa Evaluation Lab',
    projectType: input.projectType,
    projectTypeLabel: input.projectType.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase()),
    difficulty: input.difficulty,
    modality: input.modality,
    compensation: input.compensation.trim(),
    hourlyRate: input.hourlyRate || 65,
    status: 'open',
    openings: input.openings || 3,
    applicantsCount: 0,
    requiredSkills: input.requiredSkills.filter(Boolean),
    domains: input.domains.filter(Boolean),
    timeCommitment: input.timeCommitment || '10-20 hrs/week',
    createdAt: new Date().toISOString(),
  };

  const updated = [newProj, ...projects];
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEYS.projects, JSON.stringify(updated));
  }
  appendAuditLog('Project Created', newProj.title);
  return newProj;
}

export function updateAdminProjectStatus(
  projectId: string,
  newStatus: 'open' | 'in_progress' | 'completed' | 'closed'
): AdminProjectItem | null {
  const projects = getStoredAdminProjects();
  const idx = projects.findIndex((p) => p.id === projectId);
  if (idx === -1) return null;

  projects[idx].status = newStatus;
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEYS.projects, JSON.stringify(projects));
  }
  appendAuditLog(`Project Status -> ${newStatus.toUpperCase()}`, projects[idx].title);
  return projects[idx];
}

export function updateAdminApplicationStatus(
  applicationId: string,
  newStatus: AdminApplicationItem['status']
): AdminApplicationItem | null {
  const apps = getStoredAdminApplications();
  const idx = apps.findIndex((a) => a.id === applicationId);
  if (idx === -1) return null;

  apps[idx].status = newStatus;
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEYS.applications, JSON.stringify(apps));
  }
  appendAuditLog(`Application ${newStatus.toUpperCase()}`, `${apps[idx].ecName} (${apps[idx].projectTitle})`);
  return apps[idx];
}

export function toggleAdminUserStatus(userId: string): AdminUserItem | null {
  const users = getStoredAdminUsers();
  const idx = users.findIndex((u) => u.id === userId);
  if (idx === -1) return null;

  const nextStatus = users[idx].status === 'active' ? 'suspended' : 'active';
  users[idx].status = nextStatus;
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEYS.users, JSON.stringify(users));
  }
  appendAuditLog(`User Account ${nextStatus.toUpperCase()}`, users[idx].email);
  return users[idx];
}

export function verifyAdminContributor(userId: string): AdminUserItem | null {
  const users = getStoredAdminUsers();
  const idx = users.findIndex((u) => u.id === userId);
  if (idx === -1) return null;

  users[idx].verificationStatus = 'verified';
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEYS.users, JSON.stringify(users));
  }
  appendAuditLog('EC Profile Verified', users[idx].name || users[idx].email);
  return users[idx];
}

export function resolveAdminRequest(
  requestId: string,
  status: 'approved' | 'rejected' | 'resolved',
  certificateId?: string
): AdminPortalRequestItem | null {
  const reqs = getStoredAdminRequests();
  const idx = reqs.findIndex((r) => r.id === requestId);
  if (idx === -1) return null;

  reqs[idx].status = status;
  if (certificateId) reqs[idx].certificateId = certificateId;
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEYS.requests, JSON.stringify(reqs));
  }
  appendAuditLog(`Request ${status.toUpperCase()}`, `${reqs[idx].requestTypeLabel}: ${reqs[idx].requesterName}`);
  return reqs[idx];
}

export function exportVerifiedEcsAsCsv(): string {
  const users = getStoredAdminUsers();
  const verifiedEcs = users.filter((u) => u.role === 'ec' && u.verificationStatus === 'verified');

  const headers = ['ID', 'Name', 'Email', 'Status', 'Verification', 'Skills', 'Earnings (USD)'];
  const rows = verifiedEcs.map((u) => [
    u.id,
    `"${(u.name || '').replace(/"/g, '""')}"`,
    u.email,
    u.status,
    u.verificationStatus,
    `"${(u.skills || []).join('; ')}"`,
    u.earnings || 0,
  ]);

  return [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
}
