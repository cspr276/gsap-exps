export function submitProjectApplication(projectId: string, customNotes?: string): PortalApplication {
  const projects = getStoredProjects();
  const project = projects.find((p) => p.id === projectId);
  if (!project) throw new Error('Project not found');

  const applications = getStoredApplications();
  const existing = applications.find((a) => a.projectId === projectId);
  if (existing) return existing;

  const newApp: PortalApplication = {
    id: `app_${Date.now().toString(36)}`,
    projectId: project.id,
    projectTitle: project.title,
    projectType: project.projectTypeLabel,
    compensation: project.compensation,
    status: 'in_review',
    statusLabel: 'Application Received',
    submittedAt: 'Just now',
    notes: customNotes || 'Application submitted via contributor portal. Standard reviewer verification initiated.',
    matchScore: project.matchScore,
  };

  const updated = [newApp, ...applications];
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(APPLICATIONS_STORAGE_KEY, JSON.stringify(updated));
  }
  return newApp;
}
